-- V11: Chat riêng giữa giáo viên và từng sinh viên (UC-29 mở rộng).

CREATE TABLE direct_chat_channels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_direct_chat_pair UNIQUE (teacher_id, student_id),
    CONSTRAINT chk_direct_chat_roles CHECK (teacher_id <> student_id)
);

ALTER TABLE chat_messages
    ADD COLUMN direct_channel_id BIGINT REFERENCES direct_chat_channels (id) ON DELETE CASCADE;

ALTER TABLE chat_messages DROP CONSTRAINT chk_chat_channel;
ALTER TABLE chat_messages ADD CONSTRAINT chk_chat_channel CHECK (
    (channel_type = 'SUBMISSION' AND submission_id IS NOT NULL AND classroom_id IS NULL AND direct_channel_id IS NULL)
    OR (channel_type = 'CLASSROOM' AND submission_id IS NULL AND classroom_id IS NOT NULL AND direct_channel_id IS NULL)
    OR (channel_type = 'DIRECT' AND submission_id IS NULL AND classroom_id IS NULL AND direct_channel_id IS NOT NULL)
);

ALTER TABLE chat_read_markers DROP CONSTRAINT chat_read_markers_channel_type_check;
ALTER TABLE chat_read_markers ADD CONSTRAINT chat_read_markers_channel_type_check
    CHECK (channel_type IN ('SUBMISSION', 'CLASSROOM', 'DIRECT'));

CREATE INDEX idx_chat_direct ON chat_messages (direct_channel_id, id DESC)
    WHERE direct_channel_id IS NOT NULL;
