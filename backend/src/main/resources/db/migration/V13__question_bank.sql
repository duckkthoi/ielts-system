CREATE TABLE question_bank_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    rubric_template_id    BIGINT       NOT NULL UNIQUE REFERENCES rubric_templates (id) ON DELETE CASCADE,
    title                 VARCHAR(150) NOT NULL,
    task_type             VARCHAR(30)  NOT NULL CHECK (task_type IN ('WRITING_TASK1', 'WRITING_TASK2', 'CUSTOM')),
    prompt                TEXT         NOT NULL,
    image_url             VARCHAR(500),
    min_words             INT CHECK (min_words IS NULL OR min_words >= 0),
    suggested_minutes     INT CHECK (suggested_minutes IS NULL OR suggested_minutes > 0),
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_question_bank_teacher_updated
    ON question_bank_items (teacher_id, updated_at DESC);
CREATE INDEX idx_question_bank_teacher_type
    ON question_bank_items (teacher_id, task_type);

CREATE TABLE question_bank_tags (
    item_id BIGINT      NOT NULL REFERENCES question_bank_items (id) ON DELETE CASCADE,
    tag     VARCHAR(50) NOT NULL,
    PRIMARY KEY (item_id, tag)
);

CREATE INDEX idx_question_bank_tags_tag ON question_bank_tags (tag);
