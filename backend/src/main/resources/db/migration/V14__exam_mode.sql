-- Hết giờ KHÔNG tự nộp: sinh viên vẫn làm tiếp được nhưng bị gắn "Quá thời gian" (BR-24), giáo viên được báo.

ALTER TABLE assignment_parts
    ADD COLUMN exam_mode             BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN exam_duration_minutes INT CHECK (exam_duration_minutes BETWEEN 1 AND 300),
    -- Bật chế độ thi thì phải có thời lượng.
    ADD CONSTRAINT chk_part_exam_duration CHECK (NOT exam_mode OR exam_duration_minutes IS NOT NULL);

-- Mỗi sinh viên thi một phần đúng một lần (BR-23): mở lại trang thì đồng hồ chạy tiếp, không đặt lại.
CREATE TABLE exam_sessions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id              BIGINT      NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    student_id           BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    started_at           TIMESTAMPTZ NOT NULL,
    ends_at              TIMESTAMPTZ NOT NULL,
    -- Lần nộp đầu tiên; nộp sau ends_at = quá thời gian.
    finished_at          TIMESTAMPTZ,
    -- Job đã báo "quá thời gian" chưa (chống báo trùng khi job chạy chồng nhau).
    overtime_notified_at TIMESTAMPTZ,
    CONSTRAINT uk_exam_session UNIQUE (part_id, student_id),
    CONSTRAINT chk_exam_session_time CHECK (ends_at > started_at)
);
CREATE INDEX idx_exam_sessions_overdue ON exam_sessions (ends_at)
    WHERE finished_at IS NULL AND overtime_notified_at IS NULL;

CREATE TABLE exam_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_session_id BIGINT      NOT NULL REFERENCES exam_sessions (id) ON DELETE CASCADE,
    type            VARCHAR(20) NOT NULL CHECK (type IN ('STARTED', 'TAB_HIDDEN', 'TAB_VISIBLE', 'PASTE',
                                                         'DISCONNECT', 'RECONNECT', 'OVERTIME', 'SUBMITTED')),
    -- Chỉ có ở PASTE: số ký tự đã dán (không lưu nội dung dán).
    paste_chars     INT CHECK (paste_chars >= 0),
    occurred_at     TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_exam_events_session ON exam_events (exam_session_id, occurred_at);
