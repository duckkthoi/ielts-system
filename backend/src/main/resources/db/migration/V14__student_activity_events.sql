-- V14: lịch sử vào/rời màn làm bài và chuyển tab khi sinh viên đang làm bài.
CREATE TABLE student_activity_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT      NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    student_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    event_type    VARCHAR(20) NOT NULL CHECK (event_type IN ('PAGE_ENTERED', 'PAGE_LEFT', 'TAB_HIDDEN', 'TAB_VISIBLE')),
    occurred_at   TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_student_activity_assignment_time
    ON student_activity_events (assignment_id, occurred_at DESC, id DESC);
CREATE INDEX idx_student_activity_student_assignment_time
    ON student_activity_events (student_id, assignment_id, occurred_at DESC, id DESC);
