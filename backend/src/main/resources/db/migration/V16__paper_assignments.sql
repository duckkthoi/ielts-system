-- Mức 4 / bước 21a: bài tập loại PAPER (viết paper học thuật theo nhóm) — docs/12.
-- Bài cũ là ESSAY, giữ nguyên hành vi. Thang điểm suy ra từ loại: ESSAY = band IELTS, PAPER = thang 10.

ALTER TABLE assignments
    ADD COLUMN kind           VARCHAR(10) NOT NULL DEFAULT 'ESSAY' CHECK (kind IN ('ESSAY', 'PAPER')),
    ADD COLUMN citation_style VARCHAR(10) CHECK (citation_style IN ('IEEE', 'APA')),
    ADD COLUMN max_group_size INT CHECK (max_group_size BETWEEN 1 AND 10),
    -- Sau mốc này sinh viên không tự đổi nhóm nữa (BR-27); NULL = tới hạn nộp.
    ADD COLUMN group_lock_at  TIMESTAMPTZ,
    -- PAPER phải có kiểu trích dẫn + cỡ nhóm; ESSAY không có các trường của paper.
    ADD CONSTRAINT chk_assignment_paper_fields CHECK (
        (kind = 'PAPER' AND citation_style IS NOT NULL AND max_group_size IS NOT NULL)
        OR (kind = 'ESSAY' AND citation_style IS NULL AND max_group_size IS NULL AND group_lock_at IS NULL));

-- Khung mục của một giai đoạn (phần) của bài PAPER (BR-29).
CREATE TABLE paper_sections (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id     BIGINT       NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    section_key VARCHAR(40)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    required    BOOLEAN      NOT NULL DEFAULT true,
    min_words   INT CHECK (min_words >= 0),
    max_words   INT CHECK (max_words > 0),
    order_no    INT          NOT NULL,
    CONSTRAINT uk_paper_section_order UNIQUE (part_id, order_no),
    CONSTRAINT uk_paper_section_key UNIQUE (part_id, section_key),
    CONSTRAINT chk_paper_section_words CHECK (min_words IS NULL OR max_words IS NULL OR min_words <= max_words)
);

CREATE TABLE paper_groups (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT       NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    -- Người tạo: giáo viên hoặc sinh viên tự lập nhóm. Nhóm sinh viên lập tự xoá khi không còn ai.
    created_by    BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_paper_group_name UNIQUE (assignment_id, name),
    -- Cho khoá ngoại kép từ paper_group_members (thành viên và nhóm phải cùng một bài).
    CONSTRAINT uk_paper_group_assignment UNIQUE (id, assignment_id)
);

CREATE TABLE paper_group_members (
    group_id      BIGINT      NOT NULL,
    assignment_id BIGINT      NOT NULL,
    student_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at     TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (group_id, student_id),
    FOREIGN KEY (group_id, assignment_id) REFERENCES paper_groups (id, assignment_id) ON DELETE CASCADE,
    -- BR-27: mỗi sinh viên thuộc tối đa một nhóm trong một bài.
    CONSTRAINT uk_paper_member_assignment UNIQUE (assignment_id, student_id)
);
