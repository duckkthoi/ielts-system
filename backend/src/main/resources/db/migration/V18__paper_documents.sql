-- Mức 4 / bước 22: tài liệu paper của nhóm, lưu theo Yjs (CRDT) — docs/12 mục 5.2.
-- Server KHÔNG hiểu nội dung Yjs: chỉ đánh số thứ tự, lưu và chuyển tiếp các gói cập nhật nhị phân.
-- Client định kỳ gộp thành snapshot (kèm JSON + chữ thuần để server đếm từ / nộp / xuất file); update đã gộp chỉ bị
-- xoá phần nội dung (payload = NULL), giữ lại người sửa + số ký tự cho thống kê đóng góp.

CREATE TABLE paper_documents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id       BIGINT      NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    group_id      BIGINT      NOT NULL REFERENCES paper_groups (id) ON DELETE CASCADE,
    -- Trạng thái Yjs đã gộp tới snapshot_seq (NULL = chưa có snapshot).
    snapshot      BYTEA,
    snapshot_seq  BIGINT      NOT NULL DEFAULT 0,
    -- Số thứ tự update lớn nhất đã cấp (tăng 1 mỗi update, cấp khi đã khoá dòng).
    last_seq      BIGINT      NOT NULL DEFAULT 0,
    content_json  JSONB,
    content_text  TEXT,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_paper_document UNIQUE (part_id, group_id),
    CONSTRAINT chk_paper_document_seq CHECK (snapshot_seq <= last_seq)
);

CREATE TABLE paper_doc_updates (
    document_id   BIGINT      NOT NULL REFERENCES paper_documents (id) ON DELETE CASCADE,
    seq           BIGINT      NOT NULL,
    -- Gói cập nhật Yjs; NULL = đã gộp vào snapshot.
    payload       BYTEA,
    -- Người sửa (thống kê đóng góp — BR-32); SET NULL nếu tài khoản bị xoá.
    author_id     BIGINT      REFERENCES users (id) ON DELETE SET NULL,
    -- Số ký tự thêm / xoá do client tính, chỉ để thống kê.
    chars_added   INT         NOT NULL DEFAULT 0 CHECK (chars_added >= 0),
    chars_removed INT         NOT NULL DEFAULT 0 CHECK (chars_removed >= 0),
    created_at    TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (document_id, seq)
);
