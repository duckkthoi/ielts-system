-- Mức 4 / bước 24: thư viện trích dẫn của nhóm viết paper — docs/12 mục 5.3, BR-30.
-- Mỗi tài liệu tham khảo lưu dạng CSL-JSON (chuẩn chung của Zotero / Mendeley / citation-js); server chỉ giữ các
-- trường CSL trong danh sách cho phép. Định dạng IEEE / APA làm ở client, danh mục sinh tự động từ trích dẫn có trong bài.

CREATE TABLE paper_references (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id    BIGINT       NOT NULL REFERENCES paper_groups (id) ON DELETE CASCADE,
    csl         JSONB        NOT NULL,
    -- DOI đã chuẩn hoá (bỏ tiền tố https://doi.org/, chữ thường) để chặn thêm trùng; NULL = tài liệu không có DOI.
    doi         VARCHAR(200),
    -- Người thêm; SET NULL nếu tài khoản bị xoá.
    created_by  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT chk_paper_reference_doi CHECK (doi IS NULL OR doi = lower(doi)),
    CONSTRAINT chk_paper_reference_csl CHECK (jsonb_typeof(csl) = 'object')
);

CREATE INDEX idx_paper_references_group ON paper_references (group_id, id);

-- Một DOI chỉ có một lần trong thư viện của một nhóm (tài liệu không có DOI thì không chặn).
CREATE UNIQUE INDEX uk_paper_reference_doi ON paper_references (group_id, doi) WHERE doi IS NOT NULL;
