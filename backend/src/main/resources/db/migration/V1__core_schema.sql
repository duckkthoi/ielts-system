-- ---------- Người dùng ----------
CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(50)  NOT NULL UNIQUE,
    password_hash        VARCHAR(100) NOT NULL,
    full_name            VARCHAR(150) NOT NULL,
    email                VARCHAR(150),
    role                 VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'TEACHER', 'STUDENT')),
    student_code         VARCHAR(30)  UNIQUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_student_code CHECK (role <> 'STUDENT' OR student_code IS NOT NULL)
);
CREATE INDEX idx_users_role ON users (role);

-- ---------- Lớp học ----------
CREATE TABLE classrooms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL UNIQUE,
    name        VARCHAR(150) NOT NULL,
    description TEXT,
    teacher_id  BIGINT       NOT NULL REFERENCES users (id),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_classrooms_teacher ON classrooms (teacher_id);

CREATE TABLE class_members (
    classroom_id BIGINT      NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    student_id   BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (classroom_id, student_id)
);
CREATE INDEX idx_class_members_student ON class_members (student_id);

-- ---------- Mẫu tiêu chí chấm (rubric template) ----------
-- owner_id NULL = mẫu của hệ thống (IELTS chuẩn), dùng chung cho mọi giáo viên.
CREATE TABLE rubric_templates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    task_type   VARCHAR(30)  NOT NULL CHECK (task_type IN ('WRITING_TASK1', 'WRITING_TASK2', 'CUSTOM')),
    description TEXT,
    owner_id    BIGINT REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE rubric_template_criteria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT       NOT NULL REFERENCES rubric_templates (id) ON DELETE CASCADE,
    name        VARCHAR(150) NOT NULL,
    description TEXT,
    max_score   NUMERIC(4, 1) NOT NULL DEFAULT 9,
    step        NUMERIC(3, 1) NOT NULL DEFAULT 0.5,
    weight      NUMERIC(5, 2) NOT NULL DEFAULT 1,
    order_no    INT          NOT NULL,
    UNIQUE (template_id, order_no)
);

CREATE TABLE rubric_template_checklist_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_id BIGINT NOT NULL REFERENCES rubric_template_criteria (id) ON DELETE CASCADE,
    content      TEXT   NOT NULL,
    order_no     INT    NOT NULL
);

-- ---------- Bài tập ----------
CREATE TABLE assignments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id    BIGINT       NOT NULL REFERENCES users (id),
    title         VARCHAR(200) NOT NULL,
    description   TEXT,
    status        VARCHAR(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    open_at       TIMESTAMPTZ,
    due_at        TIMESTAMPTZ,
    allow_late    BOOLEAN      NOT NULL DEFAULT FALSE,
    max_revisions INT          NOT NULL DEFAULT 2 CHECK (max_revisions >= 0),
    published_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_assignment_dates CHECK (open_at IS NULL OR due_at IS NULL OR open_at < due_at)
);
CREATE INDEX idx_assignments_teacher ON assignments (teacher_id);
CREATE INDEX idx_assignments_status_due ON assignments (status, due_at);

CREATE TABLE assignment_parts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id     BIGINT       NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    order_no          INT          NOT NULL,
    title             VARCHAR(200) NOT NULL,
    task_type         VARCHAR(30)  NOT NULL DEFAULT 'CUSTOM' CHECK (task_type IN ('WRITING_TASK1', 'WRITING_TASK2', 'CUSTOM')),
    prompt            TEXT         NOT NULL,
    image_url         VARCHAR(500),
    min_words         INT CHECK (min_words IS NULL OR min_words >= 0),
    suggested_minutes INT CHECK (suggested_minutes IS NULL OR suggested_minutes > 0),
    part_due_at       TIMESTAMPTZ, -- NULL = dùng hạn của bài tập
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (assignment_id, order_no)
);

CREATE TABLE rubric_criteria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id     BIGINT        NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    name        VARCHAR(150)  NOT NULL,
    description TEXT,
    max_score   NUMERIC(4, 1) NOT NULL DEFAULT 9,
    step        NUMERIC(3, 1) NOT NULL DEFAULT 0.5,
    weight      NUMERIC(5, 2) NOT NULL DEFAULT 1,
    order_no    INT           NOT NULL,
    UNIQUE (part_id, order_no)
);

CREATE TABLE checklist_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_id BIGINT NOT NULL REFERENCES rubric_criteria (id) ON DELETE CASCADE,
    content      TEXT   NOT NULL,
    order_no     INT    NOT NULL
);

-- Giao bài: mỗi dòng trỏ tới đúng MỘT lớp hoặc MỘT sinh viên.
CREATE TABLE assignment_targets (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT      NOT NULL REFERENCES assignments (id) ON DELETE CASCADE,
    classroom_id  BIGINT REFERENCES classrooms (id) ON DELETE CASCADE,
    student_id    BIGINT REFERENCES users (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_target_one CHECK (num_nonnulls(classroom_id, student_id) = 1)
);
CREATE UNIQUE INDEX uq_target_class ON assignment_targets (assignment_id, classroom_id) WHERE classroom_id IS NOT NULL;
CREATE UNIQUE INDEX uq_target_student ON assignment_targets (assignment_id, student_id) WHERE student_id IS NOT NULL;
CREATE INDEX idx_targets_classroom ON assignment_targets (classroom_id);
CREATE INDEX idx_targets_student ON assignment_targets (student_id);

-- ---------- Bài nộp ----------
-- Mỗi (phần, sinh viên) có một submission; mỗi lần nộp tạo một submission_version bất biến.
CREATE TABLE submissions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    part_id         BIGINT      NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    student_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status          VARCHAR(30) NOT NULL DEFAULT 'NOT_STARTED'
        CHECK (status IN ('NOT_STARTED', 'DRAFT', 'SUBMITTED', 'GRADED', 'RETURNED', 'REVISION_REQUESTED')),
    current_version INT         NOT NULL DEFAULT 0,
    draft_content   TEXT,
    draft_saved_at  TIMESTAMPTZ,
    revision_due_at TIMESTAMPTZ,
    revision_note   TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (part_id, student_id)
);
CREATE INDEX idx_submissions_student ON submissions (student_id);
CREATE INDEX idx_submissions_status ON submissions (status);

CREATE TABLE submission_versions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT      NOT NULL REFERENCES submissions (id) ON DELETE CASCADE,
    version_no    INT         NOT NULL CHECK (version_no >= 1),
    content       TEXT        NOT NULL,
    word_count    INT         NOT NULL,
    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_late       BOOLEAN     NOT NULL DEFAULT FALSE,
    UNIQUE (submission_id, version_no)
);

-- ---------- Chấm bài ----------
CREATE TABLE grades (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_version_id BIGINT      NOT NULL UNIQUE REFERENCES submission_versions (id) ON DELETE CASCADE,
    grader_id             BIGINT      NOT NULL REFERENCES users (id),
    overall_score         NUMERIC(3, 1),
    general_comment       TEXT,
    status                VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'RETURNED')),
    returned_at           TIMESTAMPTZ,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE grade_criterion_scores (
    grade_id     BIGINT NOT NULL REFERENCES grades (id) ON DELETE CASCADE,
    criterion_id BIGINT NOT NULL REFERENCES rubric_criteria (id) ON DELETE CASCADE,
    score        NUMERIC(3, 1),
    comment      TEXT,
    PRIMARY KEY (grade_id, criterion_id)
);

CREATE TABLE grade_checklist_marks (
    grade_id          BIGINT  NOT NULL REFERENCES grades (id) ON DELETE CASCADE,
    checklist_item_id BIGINT  NOT NULL REFERENCES checklist_items (id) ON DELETE CASCADE,
    checked           BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (grade_id, checklist_item_id)
);

CREATE TABLE inline_comments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_id     BIGINT      NOT NULL REFERENCES grades (id) ON DELETE CASCADE,
    start_offset INT         NOT NULL CHECK (start_offset >= 0),
    end_offset   INT         NOT NULL,
    quote        TEXT,
    comment      TEXT        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_offsets CHECK (end_offset > start_offset)
);
CREATE INDEX idx_inline_comments_grade ON inline_comments (grade_id);

-- ---------- Thông báo ----------
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type       VARCHAR(50)  NOT NULL,
    title      VARCHAR(200) NOT NULL,
    body       TEXT,
    link       VARCHAR(500),
    read_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user ON notifications (user_id, created_at DESC);
CREATE INDEX idx_notifications_unread ON notifications (user_id) WHERE read_at IS NULL;

-- Chống gửi nhắc hạn nộp trùng lặp.
CREATE TABLE reminder_log (
    part_id    BIGINT      NOT NULL REFERENCES assignment_parts (id) ON DELETE CASCADE,
    student_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    kind       VARCHAR(20) NOT NULL CHECK (kind IN ('H24', 'H2', 'REVISION_H24', 'REVISION_H2')),
    sent_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (part_id, student_id, kind)
);
