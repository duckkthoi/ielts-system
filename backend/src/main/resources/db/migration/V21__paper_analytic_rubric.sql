-- Mức 4 / bước 25b: chấm bài PAPER thang 10 theo rubric phân tích (BR-31) — docs/12 mục 5.4.

-- 1) Thang 10 cho phép bước 0,25 (B21a) nhưng các cột dưới chỉ có 1 chữ số thập phân: 0,25 bị PostgreSQL làm tròn
--    thành 0,3 khi lưu. Nới sang 2 chữ số; giới hạn của mục "Giới hạn điểm" nới tới 10 cho bài PAPER.
ALTER TABLE rubric_criteria ALTER COLUMN step TYPE NUMERIC(4, 2);
ALTER TABLE grade_criterion_scores ALTER COLUMN score TYPE NUMERIC(4, 2);
ALTER TABLE checklist_items ALTER COLUMN max_band TYPE NUMERIC(4, 2);
ALTER TABLE checklist_items DROP CONSTRAINT IF EXISTS checklist_items_max_band_check;
ALTER TABLE checklist_items
    ADD CONSTRAINT chk_checklist_max_band CHECK (max_band IS NULL OR (max_band >= 0 AND max_band <= 10));

-- 2) Mức đạt của một tiêu chí (vd Xuất sắc 9–10 / Tốt 7–8,75 / Đạt 5–6,75 / Chưa đạt 0–4,75): giáo viên chọn mức rồi
--    chọn điểm trong khoảng của mức. Chỉ tiêu chí của bài PAPER có (server kiểm tra). Sống chết theo tiêu chí.
CREATE TABLE rubric_levels (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criterion_id BIGINT        NOT NULL REFERENCES rubric_criteria (id) ON DELETE CASCADE,
    label        VARCHAR(50)   NOT NULL,
    min_score    NUMERIC(4, 2) NOT NULL,
    max_score    NUMERIC(4, 2) NOT NULL,
    descriptor   TEXT,
    order_no     INT           NOT NULL,
    CONSTRAINT uk_rubric_level_order UNIQUE (criterion_id, order_no),
    CONSTRAINT chk_rubric_level_range CHECK (min_score >= 0 AND min_score <= max_score)
);

-- Mức giáo viên đã chọn khi chấm (NULL = chấm điểm trực tiếp, không chọn mức).
ALTER TABLE grade_criterion_scores
    ADD COLUMN level_id BIGINT REFERENCES rubric_levels (id) ON DELETE SET NULL;

-- 3) Điểm cộng / trừ riêng của từng thành viên nhóm trên một kết quả chấm (docs/12 mục 5.4): tối đa ±2, bắt buộc lý do.
--    Điểm của thành viên = điểm cả bài + delta, kẹp trong [0, 10].
CREATE TABLE grade_member_adjustments (
    grade_id   BIGINT        NOT NULL REFERENCES grades (id) ON DELETE CASCADE,
    student_id BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    delta      NUMERIC(3, 2) NOT NULL CHECK (delta <> 0 AND delta BETWEEN -2 AND 2),
    reason     TEXT          NOT NULL,
    PRIMARY KEY (grade_id, student_id)
);
