-- Nhận xét của giáo viên trên tài liệu Paper đang viết (B25c-live).
CREATE TABLE paper_live_comments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id   BIGINT      NOT NULL REFERENCES paper_documents (id) ON DELETE CASCADE,
    author_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    start_offset  INT         NOT NULL CHECK (start_offset >= 0),
    end_offset    INT         NOT NULL CHECK (end_offset > start_offset),
    quote         TEXT        NOT NULL,
    comment       TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL,
    updated_at    TIMESTAMPTZ NOT NULL,
    CONSTRAINT chk_paper_live_comment_lengths CHECK (end_offset - start_offset <= 10000)
);
CREATE INDEX idx_paper_live_comments_document ON paper_live_comments (document_id, start_offset, id);
