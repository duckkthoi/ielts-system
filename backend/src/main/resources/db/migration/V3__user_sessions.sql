-- =====================================================================
-- V3: Phiên đăng nhập + refresh token (docs/04-erd.md mục 4.1)
-- Một phiên giữ đúng một refresh token hợp lệ; token được xoay vòng mỗi lần refresh.
-- Chỉ lưu SHA-256 của token, không lưu token gốc.
-- =====================================================================

CREATE TABLE user_sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    refresh_token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    previous_token_hash VARCHAR(64), -- hash trước lần xoay vòng gần nhất: dùng lại → nghi bị đánh cắp
    rotated_at          TIMESTAMPTZ,  -- thời điểm xoay vòng gần nhất (tính thời gian ân hạn)
    ip                  VARCHAR(45),
    user_agent          VARCHAR(300),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_used_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at          TIMESTAMPTZ  NOT NULL,
    revoked_at          TIMESTAMPTZ,
    revoke_reason       VARCHAR(30)
        CHECK (revoke_reason IN ('LOGOUT', 'NEW_LOGIN', 'PASSWORD_CHANGED', 'ADMIN_FORCED', 'TOKEN_REUSE', 'ACCOUNT_LOCKED')),
    CONSTRAINT chk_revoked CHECK ((revoked_at IS NULL) = (revoke_reason IS NULL))
);

CREATE INDEX idx_user_sessions_active ON user_sessions (user_id) WHERE revoked_at IS NULL;
CREATE INDEX idx_user_sessions_previous ON user_sessions (previous_token_hash) WHERE previous_token_hash IS NOT NULL;
