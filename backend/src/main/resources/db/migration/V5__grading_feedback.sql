-- Nhóm tiêu chí dùng cho mã lỗi và ngân hàng nhận xét: TASK = TA (Task 1) hoặc TR (Task 2),
-- để cùng một mã lỗi (IRR, DEV…) dùng được cho cả hai loại Task.

-- ---------- Mã lỗi (BR-21, BR-22) ----------
-- owner_id NULL = mã của hệ thống (không sửa / xoá được); khác NULL = mã riêng của giáo viên.
CREATE TABLE error_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id    BIGINT REFERENCES users (id) ON DELETE CASCADE,
    code        VARCHAR(20)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    criterion   VARCHAR(10) CHECK (criterion IN ('TASK', 'CC', 'LR', 'GRA')), -- NULL = không gắn tiêu chí
    description TEXT,
    positive    BOOLEAN      NOT NULL DEFAULT FALSE, -- mã khen (GOOD), không tính là lỗi khi tổng hợp
    order_no    INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Không trùng mã trong cùng một chủ sở hữu (không phân biệt hoa thường).
-- Mã riêng trùng mã hệ thống do service chặn (ràng buộc chéo hai nhóm không viết được bằng UNIQUE).
CREATE UNIQUE INDEX uq_error_codes_system ON error_codes (upper(code)) WHERE owner_id IS NULL;
CREATE UNIQUE INDEX uq_error_codes_owner ON error_codes (owner_id, upper(code)) WHERE owner_id IS NOT NULL;

-- ---------- Ngân hàng nhận xét (BR-22) ----------
-- owner_id NULL = nhận xét mẫu của hệ thống (chỉ đọc); khác NULL = của giáo viên.
CREATE TABLE comment_bank (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT REFERENCES users (id) ON DELETE CASCADE,
    criterion    VARCHAR(10) CHECK (criterion IN ('TASK', 'CC', 'LR', 'GRA')), -- NULL = dùng chung
    content      TEXT        NOT NULL CHECK (length(content) BETWEEN 1 AND 2000),
    use_count    INT         NOT NULL DEFAULT 0 CHECK (use_count >= 0),
    last_used_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_comment_bank_owner ON comment_bank (owner_id, use_count DESC);

-- ---------- Nhận xét inline: mã lỗi, tiêu chí, gợi ý sửa (BR-21) ----------
-- error_code lưu dạng chữ (bản chụp): giáo viên xoá mã riêng thì nhận xét cũ vẫn giữ nguyên.
ALTER TABLE inline_comments
    ADD COLUMN error_code   VARCHAR(20),
    ADD COLUMN criterion_id BIGINT REFERENCES rubric_criteria (id) ON DELETE SET NULL,
    ADD COLUMN suggestion   TEXT,
    ALTER COLUMN comment DROP NOT NULL,
    ADD CONSTRAINT chk_inline_has_content CHECK (num_nonnulls(error_code, comment, suggestion) >= 1);

-- ---------- Kết quả chấm ----------
ALTER TABLE grades
    -- BR-19: "Chấm 0" bắt buộc có lý do.
    ADD COLUMN zero_reason VARCHAR(20) CHECK (zero_reason IN ('NO_ATTEMPT', 'NOT_ENGLISH', 'MEMORISED')),
    -- BR-12: band của phần giữ số thực, chỉ làm tròn khi hiển thị. NUMERIC(3,1) cũ làm mất phần lẻ (6.25 → 6.3).
    ALTER COLUMN overall_score TYPE NUMERIC(8, 6);

