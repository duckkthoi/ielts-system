-- action là danh sách mở (thêm hành động mới không cần migration), nên không đặt CHECK;
-- giá trị hợp lệ do enum AuditAction trong code quyết định.
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT REFERENCES users (id) ON DELETE SET NULL, -- NULL = hệ thống / chưa đăng nhập
    action      VARCHAR(50) NOT NULL,
    target_type VARCHAR(30),
    target_id   BIGINT,
    ip          VARCHAR(45),                                     -- IPv4 hoặc IPv6
    detail      JSONB,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_logs_created ON audit_logs (created_at DESC);
CREATE INDEX idx_audit_logs_actor ON audit_logs (actor_id, created_at DESC);
