CREATE TABLE chat_messages (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_type  VARCHAR(20) NOT NULL CHECK (channel_type IN ('SUBMISSION', 'CLASSROOM')),
    submission_id BIGINT REFERENCES submissions (id) ON DELETE CASCADE,
    classroom_id  BIGINT REFERENCES classrooms (id) ON DELETE CASCADE,
    sender_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    content       TEXT        NOT NULL CHECK (length(content) BETWEEN 1 AND 4000),
    -- Client tự sinh cho mỗi tin: khớp "đã gửi" và chống lưu trùng khi gửi lại sau lúc mất mạng.
    client_msg_id VARCHAR(40),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Loại kênh phải khớp đúng một khoá ngoại.
    CONSTRAINT chk_chat_channel CHECK (
        (channel_type = 'SUBMISSION' AND submission_id IS NOT NULL AND classroom_id IS NULL)
        OR (channel_type = 'CLASSROOM' AND classroom_id IS NOT NULL AND submission_id IS NULL)),
    CONSTRAINT uq_chat_client_msg UNIQUE (sender_id, client_msg_id)
);
CREATE INDEX idx_chat_submission ON chat_messages (submission_id, id DESC) WHERE submission_id IS NOT NULL;
CREATE INDEX idx_chat_classroom ON chat_messages (classroom_id, id DESC) WHERE classroom_id IS NOT NULL;

-- "Đã xem": tin cuối cùng mỗi người đã đọc trong mỗi kênh. channel_ref_id = submission_id hoặc classroom_id.
CREATE TABLE chat_read_markers (
    user_id              BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    channel_type         VARCHAR(20) NOT NULL CHECK (channel_type IN ('SUBMISSION', 'CLASSROOM')),
    channel_ref_id       BIGINT      NOT NULL,
    last_read_message_id BIGINT      NOT NULL,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, channel_type, channel_ref_id)
);
